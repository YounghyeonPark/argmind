//! **The deterministic side says WHERE, and WHETHER. The probabilistic side says WHAT.**
//!
//! The port of `argmind/core/`. Like it, this crate names no platform: no `windows-rs`, no audio,
//! no HTTP client. What an environment must provide is traits in [`contract`], for the reason they
//! are protocols there — the core calls them and nothing else about the machine reaches it.
//!
//! Every module here is verified against the Python it replaces, by data rather than by reading:
//!
//! | what | against | cases |
//! |---|---|---|
//! | [`converse::render`] | the prompt fingerprint `r322a4c` | 6 probes, byte-identical |
//! | [`llm::first_object`] | 128 recorded replies plus 10 synthetic | 138 |
//! | [`session`]'s pure half | the golden transcript's scene data | 66 |
//! | [`session::Session::think`] | the same scenes, whole turns | 21 scenarios, 23 turns |
//!
//! `tests/equivalence.rs` runs all four. The expectations are generated by
//! `native/expectations.py` from the shipped Python, which is the only thing Python is still for:
//! **a port needs both implementations while it is a port, and not afterwards.**

pub mod contract;
pub mod converse;
pub mod errand;
pub mod rule;
pub mod intent;
pub mod llm;
pub mod mind;
